# i18n.py
"""
Локализация приложения.
Языки: ru (базовый), en, es, de, fr, zh.

Как добавить язык:
1. Добавьте код в LANGUAGES.
2. Скопируйте словарь "ru", переведите и положите в TRANSLATIONS под новым кодом.
"""

LANGUAGES = {
    "ru": "Русский",
    "en": "English",
    "es": "Español",
    "de": "Deutsch",
    "fr": "Français",
}

DEFAULT_LANG = "ru"

_current = {"lang": DEFAULT_LANG}


def set_language(lang: str):
    _current["lang"] = lang if lang in LANGUAGES else DEFAULT_LANG


def get_language() -> str:
    return _current["lang"]


def tr(key: str, **kwargs):
    """Возвращает строку (или список строк для инструкций) на текущем языке."""
    lang = _current["lang"]
    value = TRANSLATIONS.get(lang, {}).get(key)
    if value is None:
        value = TRANSLATIONS[DEFAULT_LANG].get(key, key)
    if kwargs and isinstance(value, str):
        try:
            value = value.format(**kwargs)
        except Exception:
            pass
    return value


